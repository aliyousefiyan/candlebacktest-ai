"""Long-only, one-symbol spot replay; signals close -> execution next open.

Risk is allocated as a percentage of currently available cash, not a dollar-risk
sized stop loss. Stop/TP same-bar ambiguity always selects stop (conservative).
"""
from __future__ import annotations
import csv
import hashlib
import json
from datetime import datetime, timezone
import math
from pathlib import Path
from .schema import INTERVALS, validate_spec
from .indicators import calculate


def read_candles(path: str|Path, symbol: str, timeframe: str) -> list[dict]:
    path=Path(path)
    step=INTERVALS[timeframe]
    with path.open("r",encoding="utf-8-sig",newline="") as f:
        reader=csv.DictReader(f)
        fields={"timestamp","symbol","open","high","low","close","volume"}
        if not reader.fieldnames or not fields.issubset(set(reader.fieldnames)):
            raise ValueError(f"CSV must contain {', '.join(sorted(fields))}")
        rows=[]
        last_time=None
        for line,raw in enumerate(reader,2):
            if raw.get("symbol") != symbol:
                raise ValueError(f"line {line}: different symbol; select a single-symbol CSV")
            try:
                dt=datetime.fromisoformat(raw["timestamp"].replace("Z","+00:00"))
                if dt.tzinfo is None:
                    raise ValueError("timezone missing")
                dt=dt.astimezone(timezone.utc)
                t=int(dt.timestamp())
                nums={k:float(raw[k]) for k in ("open","high","low","close","volume")}
                if any(not math.isfinite(v) for v in nums.values()):
                    raise ValueError("non-finite value")
                o,h,l,c,v=(nums[k] for k in ("open","high","low","close","volume"))
                if min(o,h,l,c)<=0 or v<0 or h<max(o,c,l) or l>min(o,c,h):
                    raise ValueError("invalid OHLCV")
                if dt.microsecond != 0 or t % step:
                    raise ValueError("timestamp not aligned to UTC timeframe")
                if last_time is not None and t-last_time!=step:
                    raise ValueError("missing, duplicated or out-of-order candle")
            except (KeyError,TypeError,ValueError,OverflowError) as exc:
                raise ValueError(f"line {line}: {exc}") from exc
            rows.append({"timestamp":dt.isoformat().replace("+00:00","Z"),"_time":t,"symbol":symbol,**nums})
            last_time=t
    if len(rows)<3:
        raise ValueError("at least three consecutive valid candles are required")
    return rows


def _compare(condition:dict, signals:dict[str,list], i:int) -> bool:
    def at(ref,idx):
        return float(ref) if isinstance(ref,(float,int)) else signals[ref][idx]
    left,right=at(condition["left"],i),at(condition["right"],i)
    if left is None or right is None: return False
    op=condition["op"]
    if op=="gt": return left>right
    if op=="gte": return left>=right
    if op=="lt": return left<right
    if op=="lte": return left<=right
    before_l,before_r=at(condition["left"],i-1),at(condition["right"],i-1)
    if before_l is None or before_r is None: return False
    if op=="crosses_above": return before_l<=before_r and left>right
    if op=="crosses_below": return before_l>=before_r and left<right
    raise ValueError("invalid operator")


def _match(group:dict, signals:dict[str,list], i:int)->bool:
    return bool(group["all"]) and all(_compare(c,signals,i) for c in group["all"])


def backtest(strategy:dict, candles:list[dict]) -> dict:
    s=validate_spec(strategy)
    if any(c.get("symbol")!=s["symbol"] for c in candles):
        raise ValueError("candles do not match strategy symbol")
    if len(candles)<3: raise ValueError("not enough candles")
    signals=calculate(candles,s["indicators"])
    spec_hash=hashlib.sha256(json.dumps(s,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode('utf-8')).hexdigest()
    digest=hashlib.sha256()
    for row in candles:
        digest.update(json.dumps({key:row[key] for key in ('timestamp','symbol','open','high','low','close','volume')},sort_keys=True,separators=(',',':')).encode('utf-8'))
        digest.update(b'\n')
    cash=s["initial_cash"]
    fee=s["fee_bps"]/10000
    slip=s["slippage_bps"]/10000
    position=None
    trades=[]
    equity=[]
    peak=cash
    max_dd=0.0
    pending=None
    skipped_late=0
    same_bar_ties=0
    for i,bar in enumerate(candles):
        # Apply orders generated by previous bar close, at this bar open.
        if pending=="exit" and position is not None:
            px=bar["open"]*(1-slip)
            proceeds=position["quantity"]*px
            exit_fee=proceeds*fee
            cash+=proceeds-exit_fee
            trades.append({"signal_time":position["signal_time"],"entry_time":position["entry_time"],
                           "exit_time":bar["timestamp"],"entry_price":round(position["entry_price"],8),
                           "exit_price":round(px,8),"quantity":round(position["quantity"],8),
                           "entry_fee":round(position["entry_fee"],8),"exit_fee":round(exit_fee,8),
                           "net_pnl":round(proceeds-exit_fee-position["entry_cost"],8),"exit_reason":"signal"})
            position=None
        elif pending=="entry" and position is None:
            px=bar["open"]*(1+slip)
            budget=cash*s["allocation_pct"]/100
            qty=budget/(px*(1+fee))
            cost=qty*px
            entry_fee=cost*fee
            cash-=cost+entry_fee
            position={"entry_price":px,"quantity":qty,"entry_cost":cost+entry_fee,"entry_fee":entry_fee,
                      "entry_time":bar["timestamp"],"signal_time":candles[i-1]["timestamp"]}
        pending=None
        if position is not None:
            entry=position["entry_price"]
            stop=entry*(1-s["sl_pct"]/100)
            tp=entry*(1+s["tp_pct"]/100)
            hit_stop=bar["low"]<=stop
            hit_tp=bar["high"]>=tp
            if hit_stop or hit_tp:
                if hit_stop and hit_tp: same_bar_ties+=1
                reason="SL" if hit_stop else "TP"
                target=stop if hit_stop else tp
                # Opening-gap rule: if open already beyond target, execute at
                # the open, not retroactively at the untradeable target.
                if reason=="SL" and bar["open"]<stop: target=bar["open"]
                if reason=="TP" and bar["open"]>tp: target=bar["open"]
                px=target*(1-slip)
                proceeds=position["quantity"]*px
                exit_fee=proceeds*fee
                cash+=proceeds-exit_fee
                trades.append({"signal_time":position["signal_time"],"entry_time":position["entry_time"],
                               "exit_time":bar["timestamp"],"entry_price":round(entry,8),"exit_price":round(px,8),
                               "quantity":round(position["quantity"],8),"entry_fee":round(position["entry_fee"],8),
                               "exit_fee":round(exit_fee,8),"net_pnl":round(proceeds-exit_fee-position["entry_cost"],8),
                               "exit_reason":reason})
                position=None
        marked=cash+(position["quantity"]*bar["close"] if position is not None else 0)
        peak=max(peak,marked)
        max_dd=max(max_dd,(peak-marked)/peak*100)
        equity.append({"time":bar["timestamp"],"equity":round(marked,6)})
        if i>=1:
            # One action per next open; exit precedence over new entry.
            if position is not None and _match(s["exit"],signals,i): pending="exit"
            elif position is None and _match(s["entry"],signals,i): pending="entry"
        if i==len(candles)-1 and pending: skipped_late+=1
    wins=sum(t["net_pnl"]>0 for t in trades)
    final_equity=equity[-1]["equity"]
    return {
        "status":"completed","version":"0.1.0","strategy_name":s["name"],"symbol":s["symbol"],
        "timeframe":s["timeframe"],"candles":len(candles),
        "input_fingerprints":{"strategy_sha256":spec_hash,"candles_sha256":digest.hexdigest(),
                              "first_candle":candles[0]["timestamp"],"last_candle":candles[-1]["timestamp"]},
        "assumptions":{"market":"spot long-only","signal":"closed candle", "entry":"next candle open",
                       "stop_tp_tie":"stop first","gap":"worse open for stop; better open for TP",
                       "same_bar_protection":True,"risk_sizing":"allocation of cash, not stop-distance risk",
                       "end_of_data":"open position marked at last close","slippage":"adverse execution",
                       "portfolio":"single symbol, no leverage/funding or short"},
        "metrics":{"starting_cash":s["initial_cash"],"final_equity":round(final_equity,6),
                   "return_pct":round((final_equity/s["initial_cash"]-1)*100,6),
                   "max_closed_bar_drawdown_pct":round(max_dd,6),"closed_trades":len(trades),
                   "win_rate_pct":round(100*wins/len(trades),4) if trades else None,
                   "fees_paid":round(sum(t["entry_fee"]+t["exit_fee"] for t in trades)+(position["entry_fee"] if position else 0),6),
                   "pending_order_unfilled_at_end":skipped_late,"same_bar_stop_tp_ties":same_bar_ties},
        "trades":trades,"equity_curve":equity,
        "open_position":({"entry_time":position["entry_time"],"quantity":round(position["quantity"],8),
                           "entry_price":round(position["entry_price"],8),"mark_price":candles[-1]["close"]} if position else None),
        "note":"Educational historical-bar simulation, not proof of tradable real-world performance."
    }
